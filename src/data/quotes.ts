// Helper to resolve joined relations for RFQs and Quotes
export function getPopulatedRfqs(): Rfq[] {
  return mockRfqs.map((rfq) => {
    const rawProduct = mockProducts.find((p) => p.id === rfq.product_id);
    const product = rawProduct ? getProductWithRelations(rawProduct) : undefined;
    const supplier = product ? product.supplier : undefined;
    return {
      ...rfq,
      product,
      supplier,
    };
  });
}

export function getPopulatedQuotes(): Quote[] {
  const populatedRfqs = getPopulatedRfqs();
  return mockQuotes.map((quote) => {
    const rfq = populatedRfqs.find((r) => r.id === quote.rfq_id);
    const supplier = mockSuppliers.find((s) => s.id === quote.supplier_id);
    return {
      ...quote,
      rfq,
      supplier,
    };
  });
}
